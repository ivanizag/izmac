package hfs

/*
The order the catalog keeps names in, which has to be the one the File Manager
searches with or a name that is there is not found.

The catalog compares two names with RelString, case insensitive and sensitive
to diacritical marks: each character is folded to upper case through one table
and given a weight through another, and the weights are compared in turn, the
shorter name first when one is the start of the other. Both tables are copied
from the ROM of the Macintosh Plus, CONVERSION_TBL and STRIP_TBL in
plus/toolbox/os_utilities.s of the disassembly, rather than worked out from
Inside Macintosh, which describes the order without listing it.
*/

// nameOrder carries the two tables
type nameOrder struct {
	upper   *[256]uint8
	weights *[256]uint16
}

func newNameOrder() *nameOrder {
	return &nameOrder{upper: upperCaseTable(), weights: weightTable()}
}

// compare orders two names as the catalog does, both in Mac OS Roman
func (o *nameOrder) compare(a []uint8, b []uint8) int {
	for i := 0; i < len(a) && i < len(b); i++ {
		wa := o.weights[o.upper[a[i]]]
		wb := o.weights[o.upper[b[i]]]
		if wa != wb {
			if wa < wb {
				return -1
			}
			return 1
		}
	}

	switch {
	case len(a) < len(b):
		return -1
	case len(a) > len(b):
		return 1
	}
	return 0
}

